// Reads design/tokens.json, writes mobile/src/lib/tokens.generated.ts, and checks that the web
// stylesheet (src/index.css) still carries the same color values. Exits 1 on any drift.
import { readFileSync, writeFileSync } from "node:fs";

const tokens = JSON.parse(readFileSync("design/tokens.json", "utf8"));
const camel = (name) => name.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const strip = (object) => Object.fromEntries(Object.entries(object).filter(([key]) => !key.startsWith("$")));

const palette = (scheme) =>
  Object.fromEntries(Object.entries(tokens.color[scheme]).map(([key, value]) => [camel(key), value]));

const generated = {
  light: palette("light"),
  dark: palette("dark"),
  space: tokens.space,
  layout: Object.fromEntries(Object.entries(tokens.layout).map(([key, value]) => [camel(key), value])),
  radius: { ios: tokens.radius.ios, android: tokens.radius.android },
  type: { ios: strip(tokens.type.ios), android: strip(tokens.type.android) },
};

writeFileSync(
  "mobile/src/lib/tokens.generated.ts",
  `// Generated by scripts/design-tokens.mjs from design/tokens.json. Do not edit by hand.\n` +
    `export const tokens = ${JSON.stringify(generated, null, 2)} as const;\n`,
);

// Web check: the light values sit in the first :root block, the dark values in :root[data-theme="dark"].
const css = readFileSync("src/index.css", "utf8");
const block = (selector) => {
  const start = css.indexOf(selector);
  return start === -1 ? "" : css.slice(start, css.indexOf("}", start));
};
const normalize = (value) => value.replace(/\s+/g, "").toLowerCase();
const drift = [];
for (const [scheme, selector] of [["light", ":root {"], ["dark", ':root[data-theme="dark"] {']]) {
  const text = block(selector);
  for (const [name, value] of Object.entries(tokens.color[scheme])) {
    const match = text.match(new RegExp(`--${name}:\\s*([^;]+);`));
    if (!match) drift.push(`${scheme} --${name}: missing in src/index.css`);
    else if (normalize(match[1]) !== normalize(value)) drift.push(`${scheme} --${name}: css ${match[1]} ≠ tokens ${value}`);
  }
}

if (drift.length) {
  console.error(`Token drift between design/tokens.json and src/index.css:\n  ${drift.join("\n  ")}`);
  process.exit(1);
}
console.log("tokens.generated.ts written; web colors match design/tokens.json.");
