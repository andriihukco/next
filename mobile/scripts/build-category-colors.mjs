// Builds src/lib/category-colors.ts from the web stylesheet's --category-* tokens.
// Run: node scripts/build-category-colors.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const css = readFileSync(resolve(here, "../../src/index.css"), "utf8");

const colors = {};
for (const [, token, value] of css.matchAll(/--category-([a-z-]+):\s*(#[0-9a-fA-F]{6});/g)) {
  colors[token] ??= value; // First declaration wins (the :root block).
}

const source = `// Generated by scripts/build-category-colors.mjs from src/index.css. Do not edit by hand.
export const CATEGORY_COLORS: Record<string, string> = ${JSON.stringify(colors, null, 2)};
`;
writeFileSync(resolve(here, "../src/lib/category-colors.ts"), source);
console.log(`categories=${Object.keys(colors).length}`);
