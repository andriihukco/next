// Builds src/data/walk-track.ts from the web app's real road geometry.
// Picks the road segment nearest Lviv's centre and cuts it to TARGET_KM.
// Run: node scripts/build-walk-track.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const routes = JSON.parse(
  readFileSync(resolve(here, "../../src/lib/fixture-routes.json"), "utf8"),
);

const TARGET_KM = 2.4;
const CENTRE = { lat: 49.8419, lng: 24.0315 }; // Rynok Square
// Dense geometry follows the street; sparse geometry cuts corners.
const MIN_POINTS = 24; // about one point per 100 m
const MAX_STEP_KM = 0.3;

const toRad = (deg) => (deg * Math.PI) / 180;
function haversineKm(a, b) {
  const dLat = toRad(b[0] - a[0]);
  const dLng = toRad(b[1] - a[1]);
  const h =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(toRad(a[0])) * Math.cos(toRad(b[0])) * Math.sin(dLng / 2) ** 2;
  return 2 * 6371 * Math.asin(Math.sqrt(h));
}

let best = null;
let bestDistance = Infinity;
for (const route of routes) {
  const pts = route.coordinates;
  for (let i = 0; i < pts.length; i++) {
    const d = haversineKm([CENTRE.lat, CENTRE.lng], pts[i]);
    if (d >= bestDistance) continue;
    // Walk forward from i until the slice reaches TARGET_KM.
    const slice = [pts[i]];
    let length = 0;
    let longestStep = 0;
    for (let j = i + 1; j < pts.length && length < TARGET_KM; j++) {
      const step = haversineKm(pts[j - 1], pts[j]);
      length += step;
      longestStep = Math.max(longestStep, step);
      slice.push(pts[j]);
    }
    // A long single step is a data jump, not a road: reject the slice.
    if (length < TARGET_KM || slice.length < MIN_POINTS || longestStep > MAX_STEP_KM) continue;
    bestDistance = d;
    best = { route: route.route, type: route.type, slice };
  }
}

if (!best) throw new Error("No dense road segment long enough for the target length");

// Round to 5 decimals (~1 m) and report the real length of the kept slice.
const coordinates = best.slice.map(([lat, lng]) => [
  Math.round(lat * 1e5) / 1e5,
  Math.round(lng * 1e5) / 1e5,
]);
let km = 0;
for (let i = 1; i < coordinates.length; i++) {
  km += haversineKm(coordinates[i - 1], coordinates[i]);
}

const source = `// Generated by scripts/build-walk-track.mjs — do not edit by hand.
// Source: src/lib/fixture-routes.json, route ${best.route} (${best.type}).
// Real road geometry, cut to ~${TARGET_KM} km.

export const WALK_TRACK = {
  name: "Центр Львова",
  routeLabel: "${best.route}",
  lengthKm: ${km.toFixed(2)},
  coordinates: ${JSON.stringify(coordinates)} as [number, number][],
} as const;
`;

writeFileSync(resolve(here, "../src/data/walk-track.ts"), source);
console.log(`points=${coordinates.length} km=${km.toFixed(3)} route=${best.route}`);
