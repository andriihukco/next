// Bundles the web's 3D vehicle layer for the MapLibre WebView page.
// Output: src/components/map/vehicle-3d.generated.ts (base64 IIFE, ASCII only).
// Run: node scripts/build-map-3d.mjs
import { build } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");

const shimPlugin = {
  name: "web-shims",
  setup(buildApi) {
    // The layer imports the web's colour helper and maplibre-gl. Swap both for shims.
    buildApi.onResolve({ filter: /^\.\/design-colors$/ }, () => ({ path: resolve(root, "map-bundle/shims.ts") }));
    buildApi.onResolve({ filter: /^maplibre-gl$/ }, () => ({ path: resolve(root, "map-bundle/shims.ts") }));
  },
};

const result = await build({
  entryPoints: [resolve(root, "map-bundle/entry.ts")],
  bundle: true,
  format: "iife",
  minify: true,
  charset: "ascii",
  write: false,
  target: "es2019",
  plugins: [shimPlugin],
});

const code = result.outputFiles[0].text;

// The selected vehicle's trip card is plain DOM styled by the web stylesheet. Copy those rules.
const css = readFileSync(resolve(root, "../src/index.css"), "utf8").replace(/\/\*[\s\S]*?\*\//g, "");
const rules = [...css.matchAll(/([^{}]+)\{([^{}]*)\}/g)]
  .filter(([, selector]) => /vehicle-plate|\.material-symbols-rounded\b/.test(selector) && !/@/.test(selector))
  .map(([, selector, body]) => `${selector.trim()} {${body}}`);
const plateCss = rules.join("\n");
const base64 = Buffer.from(code, "utf8").toString("base64");
const source = `// Generated by scripts/build-map-3d.mjs from src/lib/vehicle-3d-layer.ts. Do not edit by hand.
export const VEHICLE_3D_BUNDLE_BASE64 = "${base64}";
export const VEHICLE_PLATE_CSS = ${JSON.stringify(plateCss)};
`;
writeFileSync(resolve(root, "src/components/map/vehicle-3d.generated.ts"), source);
console.log(`bundle bytes=${code.length} base64=${base64.length} plateRules=${rules.length}`);
